test_that("bounded concentration accounts for individual capacities", {
  M <- matrix(c(1,1,0,0),1)
  f <- check_feasibility(M,.6,lower=c(0,.1,0,0),upper=c(.15,.7,.4,.4))
  expect_equal(f$min_max_weight,.45,tolerance=1e-7)
  expect_false(f$exact)
  g <- check_feasibility(matrix(c(1,0,0,0),1),.97,upper=.5)
  expect_equal(g$min_max_weight,.5,tolerance=1e-7)
})
test_that("roundoff just above one is explicitly corrected", {
  expect_warning(a <- audit_calibration(matrix(1,1,1),1+.Machine$double.eps,raw=1),"roundoff")
  expect_equal(a$raw$ledger$target,1)
  expect_equal(a$raw$gap,0)
  expect_error(check_feasibility(matrix(1,1,1),1+1e-8),"target")
})
test_that("categorical input keeps unsupported target levels", {
  z <- calibration_matrix(data.frame(region=c("a","a","b")),list(region=c(a=.5,b=.25,c=.25)))
  expect_equal(z$M,rbind(c(1,1,0),c(0,0,1),c(0,0,0)),ignore_attr=TRUE)
  expect_equal(z$target,c(.5,.25,.25))
  expect_equal(z$margin,rep("region",3))
  expect_equal(z$level,c("a","b","c"))
  expect_equal(check_feasibility(z$M,z$target)$lower,.25)
  expect_error(calibration_matrix(data.frame(region="d"),list(region=c(a=1))),"Unknown")
})
test_that("integer guard and adaptive retry remain explicit", {
  expect_error(verify_certificate(diag(2),c(1,1),2,c(2^50,1),c(0,0),1),"range")
  M <- diag(2); f <- check_feasibility(M,c(1/3,2/3),1e-12,target_num=c(1,2),target_den=3)
  expect_true(f$exact)
  expect_gt(f$certificate$resolution,2^20)
  expect_null(rationalize_certificate(M,c(1,1),2^50,f))
})
