test_that("exact certificates distinguish inclusive ties from infeasibility", {
  M <- rbind(c(1,0),c(0,1),c(1,0),c(0,1))
  f <- check_feasibility(M,c(.75,.25,.25,.75),.25,target_num=c(3,1,1,3),target_den=4)
  expect_identical(f$status,"attainable_to_tolerance")
  expect_true(f$exact)
  expect_equal(f$certificate$upper,.25)
  f <- check_feasibility(M,c(.75,.25,.25,.75),.249,target_num=c(3,1,1,3),target_den=4)
  expect_identical(f$status,"infeasible_to_tolerance")
  expect_identical(check_feasibility(diag(2),c(.5,.5),1e-14)$status,"attainable_to_tolerance")
})
test_that("box constraints and concentration distinguish attainable from practical", {
  M <- matrix(c(1,0,0,0),1)
  a <- check_feasibility(M,.97)
  expect_equal(a$min_max_weight,.97,tolerance=1e-7)
  b <- check_feasibility(M,.97,upper=.5)
  expect_equal(b$lower,.47,tolerance=1e-7)
  expect_equal(b$upper,.47,tolerance=1e-7)
  expect_false(b$exact)
  expect_identical(b$status,"infeasible_to_tolerance")
  expect_identical(check_feasibility(diag(2),c(.5,.5),lower=.6)$status,"empty_weight_domain")
  expect_error(check_feasibility(M,.9,lower=.6,upper=.5),"exceeds")
  expect_error(check_feasibility(M,.9,upper=c(1,1)),"bounds")
  expect_equal(check_feasibility(M,.4,lower=c(.3,.1,.1,.1),upper=c(.6,.4,.4,.4))$upper,0,tolerance=1e-8)
  x <- audit_calibration(M,.97,raw=c(.97,.01,.01,.01),upper=.5)
  expect_true(x$raw$balanced)
  expect_false(x$raw$within_weight_bounds)
  expect_equal(x$raw$bound_violation,.47,tolerance=1e-7)
})
test_that("feasibility-only and labelled producer diagnostics work", {
  a <- audit_calibration(diag(2),c(.5,.5))
  expect_null(a$raw)
  expect_identical(a$feasibility$status,"attainable_to_tolerance")
  expect_warning(audit_calibration(diag(2),c(.5,.4),raw=c(1,1),margin=c("A","A")),"inconsistent")
  b <- audit_calibration(diag(2),c(.5,.5),raw=c(1,1),margin=c("A","A"),level=c("x","y"))
  expect_identical(b$raw$ledger$level,c("x","y"))
  expect_identical(b$raw$ledger$margin,c("A","A"))
})
test_that("validation rejects malformed data and exact overflow", {
  expect_error(check_feasibility(matrix(.5,1),.5),"binary")
  expect_error(check_feasibility(diag(2),c(NA,.5)),"target")
  expect_error(check_feasibility(diag(2),c(.5,.5),0),"tolerance")
  expect_error(check_feasibility(diag(2),c(.5,.5),target_num=c(1,1)),"both")
  expect_error(check_feasibility(diag(2),c(.5,.5),target_num=c(1,2),target_den=2),"match")
  expect_error(audit_calibration(diag(2),c(.5,.5),converged=1),"flag")
  expect_error(verify_certificate(matrix(c(1,0),1),2^40,2^41,c(1e6,1e6),1,1),"range")
  expect_error(verify_certificate(diag(2),c(1,1),0,c(1,1),c(1,1),2),"rational")
  expect_error(verify_certificate(diag(2),c(1,1),2,c(1,1),c(2,2),2),"witness")
})
test_that("six synthetic support-pattern cases obtain exact certificates at both tolerances", {
  for (z in six_cases) for(tol in c(1e-6,1e-3)) {
    a <- check_feasibility(z$M,z$num/z$den,tol,target_num=z$num,target_den=z$den)
    expect_true(a$exact)
    expect_identical(a$status,if(z$opt>tol) "infeasible_to_tolerance" else "attainable_to_tolerance")
    expect_lte(a$certificate$lower,z$opt+1e-10)
    expect_gte(a$certificate$upper,z$opt-1e-10)
    expect_equal(a$upper,z$opt,tolerance=1e-7)
  }
})
